# ---------------------------------------------------------------- 日期工具
def is_leap(y):
    return (y % 4 == 0 and y % 100 != 0) or y % 400 == 0


def days_of_year(y):
    return 366 if is_leap(y) else 365


def doy(y, m, d):
    """公历日期 -> 该年 0-based 日序（1/1 = 0）。"""
    n = d - 1
    for i in range(m - 1):
        n += MONTH_DAYS[i]
    if m > 2 and is_leap(y):
        n += 1
    return n


def add_days(y, m, d, delta):
    """日期加减天数，自动跨年，返回 (y, m, d)。节日算到次年时用得上。"""
    n = doy(y, m, d) + delta
    while n < 0:
        y -= 1
        n += days_of_year(y)
    while n >= days_of_year(y):
        n -= days_of_year(y)
        y += 1
    for i in range(12):
        md = MONTH_DAYS[i] + (1 if i == 1 and is_leap(y) else 0)
        if n < md:
            return y, i + 1, n + 1
        n -= md
    return y, 12, 31


def weekday(y, m, d):
    """蔡勒公式，返回 0=周一 … 6=周日。全整数，避开 float32。"""
    if m < 3:
        m += 12
        y -= 1
    c, yy = y // 100, y % 100
    w = (yy + yy // 4 + c // 4 - 2 * c + 26 * (m + 1) // 10 + d - 1) % 7
    return (w + 6) % 7      # 蔡勒原式 w: 0=周六，转成 0=周一


def nth_weekday(y, m, target, n):
    """第 n 个星期 target 在该月的日号。"""
    d = 1 + ((target - weekday(y, m, 1)) % 7) + 7 * (n - 1)
    return d if d <= MONTH_DAYS[m - 1] + (1 if m == 2 and is_leap(y) else 0) else None


# ---------------------------------------------------------------- 农历
def months_of(ly):
    """农历年 -> (春节日序, [(月,是否闰)…], [每月天数…])。"""
    if not (YEAR_MIN <= ly <= YEAR_MAX):
        return None
    spring, leap, mask = LUNAR[ly - YEAR_MIN]
    out = []
    for m in range(1, 13):
        out.append((m, False))
        if leap == m:
            out.append((m, True))
    sizes = [30 if (mask >> i) & 1 else 29 for i in range(len(out))]
    return spring, out, sizes


def solar_to_lunar(y, m, d):
    """公历 -> 农历 {"y","m","d","leap"}。春节前归上一年。"""
    if not (YEAR_MIN <= y <= YEAR_MAX):
        return None
    n = doy(y, m, d)
    spr = LUNAR[y - YEAR_MIN][0]
    if n < spr:
        ly = y - 1
        if ly < YEAR_MIN:
            return None
        offset = days_of_year(ly) - LUNAR[ly - YEAR_MIN][0] + n
    else:
        ly = y
        offset = n - spr
    info = months_of(ly)
    if not info:
        return None
    _spring, out, sizes = info
    for i, sz in enumerate(sizes):
        if offset < sz:
            mm, lp = out[i]
            return {"y": ly, "m": mm, "d": offset + 1, "leap": lp}
        offset -= sz
    return None


def lunar_to_solar(ly, lm, ld, is_leap_month=False):
    """农历 -> 公历 (y, m, d)。"""
    info = months_of(ly)
    if not info:
        return None
    spring, out, sizes = info
    n = spring
    for i, pair in enumerate(out):
        if pair == (lm, is_leap_month):
            n += ld - 1
            return add_days(ly, 1, 1, n)
        n += sizes[i]
    return None


def ganzhi(ly):
    """干支 + 生肖，以正月初一为年界（民俗口径，不按立春）。"""
    i = (ly - 4) % 60
    return GAN[i % 10] + ZHI[i % 12], ANIMALS[i % 12]


def lunar_cn(l):
    if not l:
        return ""
    pre = "闰" if l["leap"] else ""
    return pre + MONTH_CN[l["m"] - 1] + "月" + DAY_CN[l["d"] - 1]


