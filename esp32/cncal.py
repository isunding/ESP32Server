def today(y, m, d):
    """供 /api/calendar 用的小 JSON。"""
    c = ensure(y)
    if not c:
        return {"ok": 0, "msg": "年份超出支持范围（2000-2100）"}
    key = "%02d%02d" % (m, d)
    l = solar_to_lunar(y, m, d)
    gz, animal = ganzhi(l["y"]) if l else ("", "")

    # 今日节气
    term = ""
    for i, dd in enumerate(c["term"]):
        if dd == d and i // 2 + 1 == m:
            term = TERMS[i]
            break

    fests = [n for n in c["events"].get(key, []) if not n.endswith("·节气")]

    # 接下来 3 个值得标记的日子。只在本公历年内找：缓存是「年度表」，
    # 跨年再用同一个 MMDD 去查会串到本年的节日上（12 月底容易误报）。
    nxt = []
    for k in range(1, 130):
        yy, mm, dd = add_days(y, m, d, k)
        if yy != y:
            break
        kk = "%02d%02d" % (mm, dd)
        names = c["events"].get(kk)
        ti = None
        for i, td in enumerate(c["term"]):
            if td == dd and i // 2 + 1 == mm:
                ti = TERMS[i]
                break
        if names or ti:
            label = [n for n in (names or []) if not n.endswith("·节气")]
            # 清明 / 冬至既是节气又是节日，别显示成「清明 / 清明节」
            if ti and not any(ti in x for x in label):
                label.insert(0, ti)
            nxt.append({"date": "%02d-%02d" % (mm, dd), "days": k,
                        "name": " / ".join(label[:2])})
            if len(nxt) >= 3:
                break

    return {
        "ok": 1, "y": y, "m": m, "d": d, "week": weekday(y, m, d),
        "lunar": lunar_cn(l),
        "lunar_full": ("农历%s年 %s" % (gz, lunar_cn(l))) if l else "",
        "ganzhi": gz, "zodiac": animal,
        "term": term, "festivals": fests,
        "next": nxt,
        "cache": {"y": c["y"], "count": c["count"]},
    }
